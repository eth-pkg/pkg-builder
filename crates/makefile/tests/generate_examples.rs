/// Test that Noble examples have extra repos in the generated Makefile.
#[test]
fn test_noble_has_extra_repos() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent().unwrap().parent().unwrap()
        .join("examples/noble/go/hello-world");
    let config = config::PkgConfig::load(&path).unwrap();
    let makefile = makefile::generate(&config).unwrap();
    assert!(makefile.contains("add-apt-repository universe"));
    assert!(makefile.contains("add-apt-repository multiverse"));
}

/// Test that virtual packages don't have runtime commands.
#[test]
fn test_virtual_no_runtime() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent().unwrap().parent().unwrap()
        .join("examples/bookworm/virtual/hello-world");
    let config = config::PkgConfig::load(&path).unwrap();
    let makefile = makefile::generate(&config).unwrap();
    // Should not have wget or language-specific commands
    assert!(!makefile.contains("go version"));
    assert!(!makefile.contains("rustc"));
}

/// Test that Go example has expected chroot commands.
#[test]
fn test_go_has_chroot_commands() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent().unwrap().parent().unwrap()
        .join("examples/bookworm/go/hello-world");
    let config = config::PkgConfig::load(&path).unwrap();
    let makefile = makefile::generate(&config).unwrap();
    assert!(makefile.contains("go version"));
    assert!(makefile.contains("chmod -R a+rwx /usr/local/go/pkg"));
    assert!(makefile.contains("ln -s /usr/local/go/bin/go /usr/bin/go"));
}

/// Test that dotnet REPEAT expands all packages.
#[test]
fn test_dotnet_repeat_expanded() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent().unwrap().parent().unwrap()
        .join("examples/noble/dotnet/hello-world");
    let config = config::PkgConfig::load(&path).unwrap();
    let makefile = makefile::generate(&config).unwrap();
    assert!(makefile.contains("dotnet --version"));
    // Should have multiple dpkg -i lines for each package
    let dpkg_count = makefile.matches("dpkg -i").count();
    assert!(dpkg_count > 5, "Expected many dpkg -i, got {}", dpkg_count);
}
