use std::path::Path;

/// Test that all example configs generate Makefiles and sbuild.conf without errors.
fn generate_for(example_dir: &str) {
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .parent()
        .unwrap()
        .join("examples")
        .join(example_dir);

    let config = config::PkgConfig::load(&path).unwrap_or_else(|e| {
        panic!("Failed to load config at {:?}: {}", path, e);
    });

    let output = makefile::generate(&config).unwrap_or_else(|e| {
        panic!("Failed to generate for {:?}: {}", path, e);
    });

    // Basic Makefile sanity checks
    assert!(output.makefile.contains("# Auto-generated by pkg-builder"));
    assert!(output.makefile.contains(".PHONY:"));
    assert!(
        output.makefile.contains("sbuild:") || output.makefile.contains("sbuild build:")
    );
    assert!(output.makefile.contains("clean:"));

    // Makefile should use SBUILD_CONFIG, not SBUILD_FLAGS
    assert!(
        output.makefile.contains("SBUILD_CONFIG="),
        "Expected SBUILD_CONFIG in Makefile for {}",
        example_dir
    );
    assert!(
        !output.makefile.contains("SBUILD_FLAGS"),
        "SBUILD_FLAGS should not appear in Makefile for {}",
        example_dir
    );

    // Basic sbuild.conf sanity checks
    assert!(output.sbuild_conf.contains("$distribution"));
    assert!(output.sbuild_conf.contains("$chroot_mode = 'unshare'"));
    assert!(output.sbuild_conf.contains("1;"));
}

