/// Test that Noble examples have extra repos in sbuild.conf.
#[test]
fn test_noble_has_extra_repos() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .parent()
        .unwrap()
        .join("examples/noble/go/hello-world");
    let config = config::PkgConfig::load(&path).unwrap();
    let output = makefile::generate(&config).unwrap();
    assert!(output.sbuild_conf.contains("add-apt-repository universe"));
    assert!(output.sbuild_conf.contains("add-apt-repository multiverse"));
}

/// Test that virtual packages don't have runtime commands.
#[test]
fn test_virtual_no_runtime() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .parent()
        .unwrap()
        .join("examples/bookworm/virtual/hello-world");
    let config = config::PkgConfig::load(&path).unwrap();
    let output = makefile::generate(&config).unwrap();
    // Should not have language-specific commands in sbuild.conf
    assert!(!output.sbuild_conf.contains("go version"));
    assert!(!output.sbuild_conf.contains("rustc"));
}

/// Test that Go example has expected chroot commands in sbuild.conf.
#[test]
fn test_go_has_chroot_commands() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .parent()
        .unwrap()
        .join("examples/bookworm/go/hello-world");
    let config = config::PkgConfig::load(&path).unwrap();
    let output = makefile::generate(&config).unwrap();
    assert!(output.sbuild_conf.contains("go version"));
    assert!(output.sbuild_conf.contains("chmod -R a+rwx /usr/local/go/pkg"));
    assert!(output.sbuild_conf.contains("ln -s /usr/local/go/bin/go /usr/bin/go"));
    // Variables should be substituted with actual values
    assert!(output.sbuild_conf.contains("go.dev/dl/go1.22.2"));
    assert!(output.sbuild_conf.contains("5901c52b"));
}

/// Test that dotnet packages are expanded with actual package values.
#[test]
fn test_dotnet_repeat_expanded() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .parent()
        .unwrap()
        .join("examples/noble/dotnet/hello-world");
    let config = config::PkgConfig::load(&path).unwrap();
    let output = makefile::generate(&config).unwrap();
    assert!(output.sbuild_conf.contains("dotnet --version"));
    // Should have actual package names (not Make variables)
    assert!(
        output.sbuild_conf.contains("netstandard-targeting-pack"),
        "Expected actual package name in sbuild.conf"
    );
    // Should NOT have Make variable references
    assert!(
        !output.sbuild_conf.contains("$(PKG"),
        "Should not have Make variable references in sbuild.conf"
    );
    // Should NOT have $(foreach) — that's a Make construct
    assert!(
        !output.sbuild_conf.contains("$(foreach"),
        "Should not have $(foreach) in sbuild.conf"
    );
}

/// Test that sbuild.conf has lintian settings when enabled.
#[test]
fn test_sbuild_conf_lintian_disabled_always() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .parent()
        .unwrap()
        .join("examples/bookworm/go/hello-world");
    let config = config::PkgConfig::load(&path).unwrap();
    let output = makefile::generate(&config).unwrap();
    assert!(output.sbuild_conf.contains("$run_lintian = 0"));
    assert!(!output.sbuild_conf.contains("$lintian_opts"));
}

