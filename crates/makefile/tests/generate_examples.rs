use std::path::Path;

/// Test that all example configs generate Makefiles without errors.
fn generate_for(example_dir: &str) {
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .unwrap()
        .parent()
        .unwrap()
        .join("examples")
        .join(example_dir);

    let config = config::PkgConfig::load(&path).unwrap_or_else(|e| {
        panic!("Failed to load config at {:?}: {}", path, e);
    });

    let makefile = makefile::generate(&config).unwrap_or_else(|e| {
        panic!("Failed to generate Makefile for {:?}: {}", path, e);
    });

    // Basic sanity checks
    assert!(makefile.contains("# Auto-generated by pkg-builder"));
    assert!(makefile.contains(".PHONY:"));
    assert!(makefile.contains("sbuild:") || makefile.contains("sbuild \\"));
    assert!(makefile.contains("clean:"));
}

